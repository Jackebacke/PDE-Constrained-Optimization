import poisson_discretization_DpDm as pd
import numpy as np
import matplotlib.pyplot as plt

def source_time_fun(t):
    """Gaussian source time function"""
    t0 = 0.3
    sigma = 0.02
    return 1e3*np.exp(-0.5*(t-t0)**2/sigma**2)

def semidiscrete_source(grid, H):
    """Return semidiscrete source (function of time)
    grid:   generated by pd.create_grid()
    H:      SBP quadrature matrix
    """

    # Source coordinates
    x, y = 0.0, 0.0

    # Build discrete delta function
    discr_delta = discrete_delta_fun(x, y, grid, H)

    # Return source time function multiplied by spatially discretized delta function
    return lambda t: source_time_fun(t)*discr_delta


def closest_index(x, y, grid):
    """Helper function for discrete delta functions.
    Finds the grid point that is closest to (x,y)."""
    X = grid['Xv']
    Y = grid['Yv']
    dist = (X-x)**2 + (Y-y)**2
    index = np.argmin(dist)
    return index

def discrete_delta_fun(x, y, grid, H):
    """Return a discrete delta function at position (x,y)
    grid:   generated by pd.create_grid()
    H:      SBP quadrature matrix
    """
    hx = grid['hx']
    hy = grid['hy']

    discr_delta = 0.0*grid['Xv']
    index = closest_index(x, y, grid)

    # Note scaling with H^{-1} to approximate delta function
    discr_delta[index] = 1/H[index, index]

    return discr_delta

def plot_project_data(filename):
    """Plot receiver layout and data from some receivers."""

    data_file = np.load(filename)
    data = data_file['data']
    x_rec = data_file['x_rec']
    y_rec = data_file['y_rec']
    dt = data_file['dt']

    # Plot receivers and locations 
    fig, ax = plt.subplots()
    ax.scatter(x_rec, y_rec, color='red', marker=(5,1), label='receivers')
    ax.scatter(0, 0, color='blue', marker=(5,1), label='source')
    ax.set_xlabel('x')
    ax.set_ylabel('y')
    ax.legend()
    ax.set_title('Receiver and source locations')

    # Receiver data points are dt apart in time
    nRec, Nt = data.shape
    tvec = dt*np.linspace(0, Nt-1, Nt)
    t0 = tvec[0]
    tend = tvec[-1]
    print(f'Initial time: t={t0}. Final time: t={tend}')

    # Plot data from 4 of the receivers
    fig, axes = plt.subplots(2, 2)
    axes = axes.flatten()
    for i in range(4):
        axes[i].plot(tvec, data[i,:])
        axes[i].set_title(f'Receiver at (x,y)=({x_rec[i]:.1f},{y_rec[i]:.1f})')
        axes[i].set_xlabel('t')
        axes[i].set_ylabel('y(t)')

def play_source_animation(mx=21, my=21):
    """Plays an animation of the source.
    The code shows how to construct and use the semidiscrete source."""

    # Domain and grid
    xlim = [-1,1]
    ylim = [-1,1]
    grid = pd.create_grid(mx, my, xlim, ylim)    

    # Build SBP matrices (b does not matter here)
    order = 5
    sbp_ops = pd.assemble_matrices(grid, order)
    H = sbp_ops['H']

    # Semidiscrete source: delta function at (x,y)=(0,0)
    # with a gaussian time function
    source_fun = semidiscrete_source(grid, H)

    # Evaluate source at t=0 and set up source plot
    t = 0.0
    source0 = source_fun(0.0)
    fig, ax, cb = initial_plot(grid, source0, t=0.0)

    # Load time step from file
    data_file = np.load('data_proj2.npz')
    dt = data_file['dt']
    T = 1.0
    Nt = round(T/dt)

    # Loop over time steps. Evaluate and plot source in every step.
    for i in range(Nt):
        t += dt
        source = source_fun(t)
        cb = update_plot(grid, fig, ax, cb, source, t)

def initial_plot(grid, z0, t=0.0):
    """Helper for setting up a plot"""
    X = grid['X']
    Y = grid['Y']
    Z0 = np.reshape(z0, X.shape)
    fig, ax = plt.subplots()
    im = ax.pcolormesh(X, Y, Z0, shading='auto')
    cb = fig.colorbar(im)
    ax.set_xlabel('x')
    ax.set_ylabel('y')
    ax.set_title(f't = {t:.2e}')
    plt.pause(1e-4)
    return fig, ax, cb

def update_plot(grid, fig, ax, cb, y, t):
    """Helper for updating an existing plot"""
    X = grid['X']
    Y = grid['Y']
    Z = np.reshape(y, X.shape)
    im = ax.pcolormesh(X, Y, Z, shading='auto')
    cb.remove()
    cb = fig.colorbar(im)
    ax.set_title(f't = {t:.2e}')
    plt.pause(1e-4)
    return cb

def main():
    # To plot source/receiver locations and some receiver data
    plot_project_data('data_proj2.npz')

    # --- Play source animation ---
    play_source_animation()

    plt.show()


if __name__ == '__main__':
    main()